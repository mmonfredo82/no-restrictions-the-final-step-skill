import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root = new URL('../', import.meta.url);
const prompt = await readFile(new URL('processing-prompt.txt', root));
const hash = createHash('sha256').update(prompt).digest('hex');
const expected = '35268620fb84ef5f78cc0dee85ca9bf672f3691ddaddf840bfeccb0c9a084196';
if (hash !== expected) throw new Error('Master v5 prompt integrity check failed.');
const skillPrompt = await readFile(new URL('skill/references/processing-prompt.txt', root));
if (!prompt.equals(skillPrompt)) throw new Error('Skill prompt differs from the master.');
const generated = `// Generated by scripts/build.mjs from the exact master bytes. Do not edit.\nexport const PROMPT = ${JSON.stringify(prompt.toString('utf8'))};\n`;
const target = new URL('src/generated-prompt.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw new Error('Generated prompt is stale. Run npm run build.');
} else await writeFile(target, generated);
console.log(`Verified v5 master: ${prompt.length} bytes, SHA-256 ${hash}`);
